import { mkdir, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { SOURCES, importJEEBench, importMainPractice, importPW } from "./question-importers.mjs";

const output = new URL("../public/question-bank/", import.meta.url);
const provenance = [];
async function download(url) {
  const response = await fetch(url, { signal: AbortSignal.timeout(60_000) });
  if (!response.ok) throw new Error(`Question source download failed (${response.status}): ${url}`);
  const text = await response.text();
  provenance.push({ url, sha256: createHash("sha256").update(text).digest("hex") });
  return text;
}
const rows = [];
const base = "https://huggingface.co/datasets/";
const bench = JSON.parse(
  await download(`${base}daman1209arora/jeebench/resolve/${SOURCES.jeebench.revision}/test.json`),
);
rows.push(...bench.map(importJEEBench));
for (const subject of ["physics", "chemistry", "mathematics"]) {
  for (const split of ["train", "test"]) {
    const text = await download(
      `${base}soughed/jee-main-questions/resolve/${SOURCES.mainPractice.revision}/${subject}/${split}.jsonl`,
    );
    rows.push(
      ...text
        .split("\n")
        .filter((line) => line.trim())
        .map((line) => importMainPractice(JSON.parse(line))),
    );
  }
}
const pwSource = SOURCES.pw;
for (const session of ["jan", "apr"]) {
  const text = await download(
    `${base}PhysicsWallahAI/JEE-Main-2025-Math/resolve/${pwSource.revision}/main2025-${session}.jsonl`,
  );
  rows.push(
    ...text
      .split("\n")
      .filter((line) => line.trim())
      .map((line, i) => importPW(JSON.parse(line), pwSource, `${session}-${i}`)),
  );
}
const unique = new Map();
for (const row of rows.filter(Boolean))
  if (!unique.has(row.id) || row.source.kind === "pyq") unique.set(row.id, row);
await mkdir(output, { recursive: true });
// The community collection has paper-provenance and transcription problems.
// Retain its importer for auditing, but never ship it as a practice source by default.
const questions = [...unique.values()].filter((q) => q.source.kind === "pyq");
for (const exam of ["jee-main", "jee-advanced"])
  await writeFile(
    new URL(`${exam}.json`, output),
    JSON.stringify(questions.filter((q) => q.exam_id === exam)),
  );
const manifest = {
  updated: new Date().toISOString(),
  count: questions.length,
  rejected: rows.filter((q) => !q).length,
  heldForReview: [...unique.values()].filter((q) => q.source.kind !== "pyq").length,
  deduplicated: rows.filter(Boolean).length - unique.size,
  sourceCounts: Object.fromEntries(
    [SOURCES.jeebench, SOURCES.mainPractice, pwSource].map((source) => [
      source.name,
      questions.filter((q) => q.source.name === source.name).length,
    ]),
  ),
  exams: Object.fromEntries(
    ["jee-main", "jee-advanced"].map((exam) => [
      exam,
      {
        count: questions.filter((q) => q.exam_id === exam).length,
        mcq: questions.filter((q) => q.exam_id === exam && q.question_type === "mcq").length,
      },
    ]),
  ),
  sources: [SOURCES.jeebench, SOURCES.mainPractice, pwSource],
  downloads: provenance,
};
await writeFile(
  new URL("LICENSE-JEEBench.txt", output),
  await download("https://raw.githubusercontent.com/dair-iitd/jeebench/main/LICENSE"),
);
await writeFile(
  new URL("LICENSE-Apache-2.0.txt", output),
  await download("https://www.apache.org/licenses/LICENSE-2.0.txt"),
);
await writeFile(
  new URL("NOTICE.md", output),
  `# Question bank attribution\n\nJEEBench: Copyright (c) 2023 Data Analytics and Intelligence Research (DAIR) Group, IIT Delhi. Daman Arora, Himanshu Singh, and Mausam. MIT license; see LICENSE-JEEBench.txt.\n\nPhysics Wallah AI Research: JEE Mains 2025 Math Evaluation Set. Apache-2.0; see LICENSE-Apache-2.0.txt.\n\nJEE Main practice collection: compiled by eQOURSE, mirrored by soughed, CC BY 4.0 as declared in the dataset card: https://creativecommons.org/licenses/by/4.0/ . Source: https://huggingface.co/datasets/soughed/jee-main-questions . Original-paper dates are not verified; these records are held for review and are excluded from every shipped question snapshot.\n\nChanges: normalized formatting and question types, separated choices, converted tables, removed incomplete or diagram-dependent questions, deduplicated, and retained source answer keys. No questions or answers are generated by AI during import.\n\nQuestions and answer keys remain attributed to their exam publishers; dataset licenses are upstream declarations. See manifest.json for pinned revisions, download checksums, counts and source URLs.\n`,
);
await writeFile(new URL("manifest.json", output), JSON.stringify(manifest, null, 2));
console.log(
  JSON.stringify(
    { imported: questions.length, excluded: manifest.rejected, exams: manifest.exams },
    null,
    2,
  ),
);
